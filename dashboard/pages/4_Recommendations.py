import sys
import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "../..")))

import streamlit as st
from dashboard.utils.data_access import (
    get_recommendations,
    update_recommendation_status,
    check_db_exists,
    get_audit_metadata
)
from dashboard.components.charts import recommendation_savings_bar

# Configure Recommendations screen
st.set_page_config(page_title="Remediation Actions - CLARA", layout="wide", page_icon="🧠")

st.title("🧠 GenAI Recommendations & Remediation")
st.write("Prioritized recommendations generated by Google Gemini. Review, approve, and audit remediation scripts.")

exists, _ = check_db_exists()
if exists:
    # Query all recommendations to feed the top bar chart
    all_recs = get_recommendations()
    
    # 1. Savings Bar Chart at the Top of the page
    if not all_recs.empty:
        fig_savings = recommendation_savings_bar(all_recs)
        st.plotly_chart(fig_savings, use_container_width=True)
        st.divider()
        
    # 2. Filters layout inside the screen
    filter_col1, filter_col2 = st.columns(2)
    with filter_col1:
        priority_filter = st.selectbox(
            "Filter by Priority:", 
            options=["All", "Critical", "High", "Medium", "Low"]
        )
    with filter_col2:
        status_filter = st.selectbox(
            "Filter by Status:", 
            options=["All", "Pending", "Approved", "Rejected", "Archived"]
        )
        
    # Query filtered list
    filtered_recs = get_recommendations(priority_filter, status_filter)
    
    # 3. Render expandable recommendation cards
    if filtered_recs.empty:
        st.info("No recommendations matching the selected filters.")
    else:
        for idx, row in filtered_recs.iterrows():
            rec_id = row["recommendation_id"]
            priority_color = {
                "Critical": "🔴",
                "High": "🟠",
                "Medium": "🟡",
                "Low": "🟢"
            }.get(row["priority"], "⚪")
            
            header = f"{priority_color} [{row['priority']}] {row['title']} (Instance: {row['instance_id']})"
            
            with st.expander(header):
                st.markdown(f"**Description:** {row['description']}")
                
                # Split implementation steps by delimiter
                st.markdown("**Actionable Remediation Steps:**")
                steps = str(row["implementation_steps"]).split(" | ")
                for step_idx, step in enumerate(steps, 1):
                    st.markdown(f"{step_idx}. {step}")
                    
                # Metadata metrics row
                m_col1, m_col2, m_col3 = st.columns(3)
                with m_col1:
                    st.metric("Estimated Effort", f"{row['estimated_effort_hours']} hrs")
                with m_col2:
                    st.metric("Estimated Savings", f"${row['estimated_savings_usd']:.2f}/mo")
                with m_col3:
                    st.metric("Current Status", row["status"].upper())
                    
                # Action approval buttons row
                act_col1, act_col2, act_col3 = st.columns(3)
                with act_col1:
                    if st.button("Approve & Execute", key=f"app_{rec_id}"):
                        update_recommendation_status(rec_id, "approved")
                        st.success(f"Recommendation {rec_id} approved!")
                        st.rerun()
                with act_col2:
                    if st.button("Reject / Dismiss", key=f"rej_{rec_id}"):
                        update_recommendation_status(rec_id, "rejected")
                        st.warning(f"Recommendation {rec_id} rejected.")
                        st.rerun()
                with act_col3:
                    if st.button("Archive Plan", key=f"arc_{rec_id}"):
                        update_recommendation_status(rec_id, "archived")
                        st.info(f"Recommendation {rec_id} archived.")
                        st.rerun()
                        
    st.divider()
    
    # 4. Governance Audit Trail
    st.subheader("📋 Governance Audit Trail")
    audit_data = get_audit_metadata()
    total_inst = audit_data["total_instances"]
    calc_time_str = audit_data["calc_time_str"]
    gen_time_str = audit_data["gen_time_str"]
    rec_count = audit_data["recommendation_count"]

    st.code(f"""
[{calc_time_str}] SYSTEM: Daily metrics ingested for {total_inst} instances (DuckDB local warehouse).
[{calc_time_str}] ANALYTICS: Ran Isolation Forest anomaly scoring and risk models.
[{gen_time_str}] GENAI: Sent high-risk instances to Gemini API for remediation guidance generation.
[{gen_time_str}] SYSTEM: Created {rec_count} recommendations with status 'Pending'.
    """, language="text")
